/**
 * Generate tsconfig.paths.json — the single `compilerOptions.paths` block that
 * both tsconfig.json and scripts/tsconfig.json extend.
 *
 * The `@addon/<id>/api` entries are derived from what is actually on disk rather
 * than hand-maintained, because the alias set grows every time an addon is added
 * and a hand-maintained list is how a new addon silently stops resolving. The
 * discovery rule mirrors tools/addon_api_plugin.js exactly: `@addon/<id>/api`
 * resolves to `addons/builtin/<id>/src/api.ts` and nowhere else.
 *
 * `paths` in an extended config are resolved relative to the config file that
 * declares them, so the repo-root-relative entries below stay correct when
 * scripts/tsconfig.json extends this from one directory down.
 *
 * @sculptcore/api is deliberately absent: it resolves through the pnpm workspace
 * symlink, and a path mapping would shadow that.
 *
 * Usage: node tools/gen-tsconfig-paths.mjs  (run by `pnpm gen:paths`)
 */
import {readdirSync, existsSync, writeFileSync, readFileSync} from 'node:fs'
import {dirname, join, resolve} from 'node:path'
import {fileURLToPath} from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(__dirname, '..')
const OUT = join(repoRoot, 'tsconfig.paths.json')

/** Aliases that are not derived from the addon tree. */
const STATIC_PATHS = {
  '@framework/api'   : ['./scripts/framework_api.ts'],
  '@framework/pathux': ['./scripts/path.ux/scripts/pathux.ts'],
}

function discoverAddonApis() {
  const builtinDir = join(repoRoot, 'addons', 'builtin')
  const paths = {}

  for (const entry of readdirSync(builtinDir, {withFileTypes: true})) {
    if (!entry.isDirectory()) {
      continue
    }
    const api = join(builtinDir, entry.name, 'src', 'api.ts')
    if (existsSync(api)) {
      paths[`@addon/${entry.name}/api`] = [`./addons/builtin/${entry.name}/src/api.ts`]
    }
  }

  return paths
}

const paths = {...STATIC_PATHS, ...discoverAddonApis()}

const contents = `${JSON.stringify(
  {
    $comment       : 'GENERATED by tools/gen-tsconfig-paths.mjs — do not edit by hand. Run `pnpm gen:paths`.',
    compilerOptions: {paths},
  },
  null,
  2
)}\n`

const previous = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null
if (previous !== contents) {
  writeFileSync(OUT, contents)
  console.log(`gen-tsconfig-paths: wrote tsconfig.paths.json (${Object.keys(paths).length} aliases)`)
} else {
  console.log(`gen-tsconfig-paths: tsconfig.paths.json up to date (${Object.keys(paths).length} aliases)`)
}
