/**
 * Generate tsconfig.paths.json — the `compilerOptions.paths` block and the
 * `exclude` list that both tsconfig.json and scripts/tsconfig.json extend.
 *
 * The `@addon/<id>/api` entries are derived from what is actually on disk rather
 * than hand-maintained, because the alias set grows every time an addon is added
 * and a hand-maintained list is how a new addon silently stops resolving. The
 * discovery rule mirrors tools/addon_api_plugin.js exactly: `@addon/<id>/api`
 * resolves to `addons/builtin/<id>/src/api.ts` and nowhere else.
 *
 * `paths` in an extended config are resolved relative to the config file that
 * declares them, so the repo-root-relative entries below stay correct when
 * scripts/tsconfig.json extends this from one directory down.
 *
 * @sculptcore/api is deliberately absent: it resolves through the pnpm workspace
 * symlink, and a path mapping would shadow that. What *is* here is the fallout
 * of that symlink going away — `git submodule deinit sculptcore` makes litemesh
 * unavailable (tools/builtin_addons.js), so its `@builtin/<id>` entry resolves
 * to the unavailable-builtin stub and its sources leave the program. `exclude`
 * is generated here rather than written in tsconfig.json because a child
 * config's `exclude` replaces its base's outright, so the two cannot be split.
 *
 * Usage: node tools/gen-tsconfig-paths.mjs  (run by `pnpm gen:paths`)
 */
import {readdirSync, existsSync, writeFileSync, readFileSync} from 'node:fs'
import {dirname, join, resolve} from 'node:path'
import {fileURLToPath} from 'node:url'

import {discoverBuiltins} from './builtin_addons.js'

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = resolve(__dirname, '..')
const OUT = join(repoRoot, 'tsconfig.paths.json')

/** Aliases that are not derived from the addon tree. */
const STATIC_PATHS = {
  '@framework/api'   : ['./scripts/framework_api.ts'],
  '@framework/pathux': ['./scripts/path.ux/scripts/pathux.ts'],
}

/** What the program never looks at, whichever addons are in the build. */
const STATIC_EXCLUDE = [
  'node_modules',
  '**/node_modules',
  'scripts/path.ux',
  'scripts/mathl',
  'build',
  'dist',
  'types',
  'archive',
]

const UNAVAILABLE_STUB = './scripts/addon/unavailable_builtin.ts'

/**
 * `@builtin/<id>` — an in-bundle builtin's entry module, as
 * addons/builtin/builtin_registry.ts imports it. It points at the stub when the
 * addon is not in this build, so the registry still compiles while the addon's
 * own sources — which import an engine that is not here — leave the program.
 */
function discoverBuiltinEntries(builtins) {
  const paths = {}
  const exclude = []

  for (const b of builtins) {
    if (b.available) {
      paths[`@builtin/${b.id}`] = [`./addons/builtin/${b.dir}/${b.manifest.entry}`]
    } else {
      paths[`@builtin/${b.id}`] = [UNAVAILABLE_STUB]
      exclude.push(`addons/builtin/${b.dir}`)
    }
  }

  return {paths, exclude}
}

function discoverAddonApis() {
  const builtinDir = join(repoRoot, 'addons', 'builtin')
  const paths = {}

  for (const entry of readdirSync(builtinDir, {withFileTypes: true})) {
    if (!entry.isDirectory()) {
      continue
    }
    const api = join(builtinDir, entry.name, 'src', 'api.ts')
    if (existsSync(api)) {
      paths[`@addon/${entry.name}/api`] = [`./addons/builtin/${entry.name}/src/api.ts`]
    }
  }

  return paths
}

const builtins = discoverBuiltins()
const entries = discoverBuiltinEntries(builtins)
const paths = {...STATIC_PATHS, ...discoverAddonApis(), ...entries.paths}
const exclude = [...STATIC_EXCLUDE, ...entries.exclude]

const contents = `${JSON.stringify(
  {
    $comment       : 'GENERATED by tools/gen-tsconfig-paths.mjs — do not edit by hand. Run `pnpm gen:paths`.',
    compilerOptions: {paths},
    exclude,
  },
  null,
  2
)}\n`

const previous = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null
if (previous !== contents) {
  writeFileSync(OUT, contents)
  console.log(
    `gen-tsconfig-paths: wrote tsconfig.paths.json (${Object.keys(paths).length} aliases, ${entries.exclude.length} addon(s) excluded)`
  )
} else {
  console.log(
    `gen-tsconfig-paths: tsconfig.paths.json up to date (${Object.keys(paths).length} aliases, ${entries.exclude.length} addon(s) excluded)`
  )
}
