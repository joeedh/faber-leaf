/**
 * Generates the committed `.wproj` fixtures the P10 file-compat tests read
 * (documentation/plans/2026-08-15-0345-serialization-and-file-compat-hardening.md §5).
 *
 * Run once, from the repo root, with a fresh `pnpm build`:
 *
 *   node tools/gen-file-compat-fixtures.mjs
 *
 * The bytes it writes are committed. The tests never regenerate them — a fixture
 * produced by the build under test proves nothing about cross-build compat.
 *
 * `curve` is the only geometry DataBlock type in the tree that an addon owns
 * (`addons/builtin/curve/src/curve.ts` — `TetMesh` and `strands` live in core,
 * see §5a of the plan), so it is what "written by a build whose addon the
 * reader does not have" has to be built from. The curve addon ships
 * `defaultEnabled: false`, which is exactly the asymmetry the fixture needs:
 * the authoring build turns it on, the default build reading it back does not
 * have it.
 */

import {execFileSync} from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import Path from 'node:path'
import {fileURLToPath} from 'node:url'

const REPO_ROOT = Path.resolve(Path.dirname(fileURLToPath(import.meta.url)), '..')
const FIXTURE_DIR = Path.join(REPO_ROOT, 'tests', 'integration', 'fixtures')
const WPROJ = Path.join(FIXTURE_DIR, 'curve-addon-scene.wproj')
const META = Path.join(FIXTURE_DIR, 'curve-addon-scene.json')

function resolveNwjsExe() {
  const exe = execFileSync(
    'node',
    ['-e', "require('nw').findpath().then(p=>process.stdout.write(p),()=>process.exit(1))"],
    {
      cwd     : REPO_ROOT,
      encoding: 'utf-8',
    }
  ).trim()
  if (!exe || !fs.existsSync(exe)) throw new Error('could not resolve the NW.js executable')
  return exe
}

/**
 * Builds the scene inside the app. Enabling an addon after startup does not
 * retro-create its `BlockSet` (Library's libmap is built in its constructor from
 * the class registry), so the file is round-tripped once first — `loadSTRUCT`
 * backfills a set for every registered type it did not see in the stream.
 */
const BUILD_SCENE = `globalThis.__evalTestResult = (() => {
  try {
    const am = window._addons
    const en = am.enable('curve')
    if (!en.ok) return {ok: false, error: 'enable(curve): ' + en.message}

    _appstate.loadFile(_appstate.createFile({save_screen: true, save_library: true}))

    const lib = _appstate.datalib
    const scene = _appstate.ctx.scene
    const CurveSpline = am.idmap.get('curve').addonAPI.exports.curve.CurveSpline
    const SceneObject = lib.libmap.object.type

    const curve = new CurveSpline()
    const v1 = curve.makeVertex([-2, 0, 0])
    const v2 = curve.makeVertex([0, 2, 0])
    const v3 = curve.makeVertex([2, 0, 0])
    curve.makeEdge(v1, v2)
    curve.makeEdge(v2, v3)
    curve.name = 'FixtureCurve'
    lib.add(curve)

    const ob = new SceneObject()
    lib.add(ob)
    ob.name = 'CurveObject'
    ob.data = curve
    curve.lib_addUser(ob)
    scene.add(ob)
    ob.graphUpdate()
    curve.graphUpdate()

    // With the screen, uncompressed: that is what the app itself writes, and a
    // screenless file is one loadFile_loadScreen throws on (see plan 5a).
    const buf = _appstate.createFile({save_screen: true, save_library: true, compress: false})
    const bytes = new Uint8Array(buf)
    require('fs').writeFileSync(${JSON.stringify(WPROJ).replace(/\\\\/g, '/')}, Buffer.from(bytes))

    return {
      ok        : true,
      bytes     : bytes.length,
      curveLibId: curve.lib_id,
      curveName : curve.name,
      obLibId   : ob.lib_id,
      obName    : ob.name,
      numVerts  : curve.verts.length,
      numEdges  : curve.edges.length,
      toolmodes : scene.toolmodes.map((t) => t.constructor.name),
      blockTypes: Object.keys(lib.libmap).sort(),
    }
  } catch (e) {
    return {ok: false, error: String(e), stack: String(e.stack)}
  }
})()`

fs.mkdirSync(FIXTURE_DIR, {recursive: true})
fs.rmSync(WPROJ, {force: true})

const dumpPath = Path.join(fs.mkdtempSync(Path.join(os.tmpdir(), 'p10fix-')), 'dump.json')
const profile = fs.mkdtempSync(Path.join(os.tmpdir(), 'p10prof-'))

execFileSync(
  resolveNwjsExe(),
  [
    REPO_ROOT,
    `--user-data-dir=${profile}`,
    '--apptest-headless',
    '--no-devtools',
    '--gen-scene',
    'empty',
    '--eval',
    BUILD_SCENE,
    '--dump',
    dumpPath,
    '--exit',
  ],
  {cwd: REPO_ROOT, encoding: 'utf-8', stdio: 'pipe', timeout: 240000}
)

if (!fs.existsSync(dumpPath)) throw new Error('NW.js wrote no dump')
const result = JSON.parse(fs.readFileSync(dumpPath, 'utf-8')).evalResult

if (!result?.ok) {
  console.error(result)
  throw new Error('fixture build failed inside the app')
}
if (!fs.existsSync(WPROJ)) throw new Error(`no fixture at ${WPROJ}`)

fs.writeFileSync(
  META,
  JSON.stringify(
    {
      note      : 'Generated by tools/gen-file-compat-fixtures.mjs. Committed; do not regenerate from a test.',
      addonSetA : ['mesh', 'sculptcore', 'curve'],
      curveLibId: result.curveLibId,
      curveName : result.curveName,
      obLibId   : result.obLibId,
      obName    : result.obName,
      numVerts  : result.numVerts,
      numEdges  : result.numEdges,
    },
    null,
    2
  ) + '\n'
)

fs.rmSync(profile, {recursive: true, force: true})
console.log(`wrote ${Path.relative(REPO_ROOT, WPROJ)} (${result.bytes} bytes)`)
console.log(JSON.stringify(result, null, 2))
